const DICTS: Record<Lang, Record<MKey, string>> = { tr, ku, en };

export type MT = (key: MKey, vars?: Record<string, string | number>) => string;

export function mt(lang: Lang): MT {
  return (key, vars) => {
    const s = DICTS[lang]?.[key] || tr[key] || String(key);
    if (!vars) return s;
    return s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
  };
}
